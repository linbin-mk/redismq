CREATE TABLE IF NOT EXISTS rmq_monitor_lease (
  `scope_id` BINARY(32) NOT NULL,
  `source_id` VARCHAR(64) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `namespace` VARCHAR(160) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `config_hash` BINARY(32) NOT NULL,
  `owner_id` CHAR(36) CHARACTER SET ascii COLLATE ascii_bin NOT NULL,
  `token` BIGINT NOT NULL DEFAULT 0,
  `lease_until_ms` BIGINT NOT NULL DEFAULT 0,
  `schema_version` INT NOT NULL DEFAULT 1,
  PRIMARY KEY (scope_id)
) ENGINE=InnoDB;

